const tables: Record<Locale, Record<Key, string>> = { en, de, ar };

export type Msg = Key;

export function translate(locale: Locale, key: Key): string {
  return tables[locale][key] ?? tables.en[key] ?? key;
}

export function isLocale(value: string): value is Locale {
  return value === "en" || value === "de" || value === "ar";
}
